from unittest.mock import patch

from django.contrib.auth import get_user_model
from django.test import RequestFactory, TestCase

from .models import Blog, Like, Playlist

User = get_user_model()


class BlogSlugTests(TestCase):
    def setUp(self):
        self.author = User.objects.create_user(username="alice", password="x")

    def test_slug_autogenerated_from_title(self):
        blog = Blog.objects.create(title="Hello World", content="c", author=self.author)
        self.assertEqual(blog.slug, "hello-world")

    def test_duplicate_titles_get_unique_slugs(self):
        b1 = Blog.objects.create(title="Same Title", content="c", author=self.author)
        b2 = Blog.objects.create(title="Same Title", content="c", author=self.author)
        self.assertNotEqual(b1.slug, b2.slug)
        self.assertEqual(b2.slug, "same-title-1")

    def test_editing_keeps_slug_stable(self):
        blog = Blog.objects.create(title="Original", content="c", author=self.author)
        original_slug = blog.slug
        blog.title = "Changed"
        blog.save()
        self.assertEqual(blog.slug, original_slug)


